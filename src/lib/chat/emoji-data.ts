const RECENT_KEY = "madlove:emoji:recent";
const MAX_RECENT = 32;

export function loadRecentEmojis(): string[] {
  if (typeof window === "undefined") return [];
  try {
    const raw = localStorage.getItem(RECENT_KEY);
    if (!raw) return [];
    const parsed = JSON.parse(raw) as unknown;
    if (!Array.isArray(parsed)) return [];
    return parsed.filter((x): x is string => typeof x === "string").slice(0, MAX_RECENT);
  } catch {
    return [];
  }
}

export function rememberEmoji(emoji: string): string[] {
  const next = [emoji, ...loadRecentEmojis().filter((e) => e !== emoji)].slice(
    0,
    MAX_RECENT,
  );
  try {
    localStorage.setItem(RECENT_KEY, JSON.stringify(next));
  } catch {
    /* ignore quota */
  }
  return next;
}

/** True when the message is mostly emoji (WhatsApp-style large render). */
export function isEmojiHeavyMessage(text: string): boolean {
  const trimmed = text.trim();
  if (!trimmed || trimmed.length > 48) return false;

  // Remove ZWJ / variation selectors / whitespace, then strip known emoji ranges
  const compact = trimmed.replace(/[\uFE0F\u200D\s]/g, "");
  if (!compact) return false;

  const withoutEmoji = compact
    .replace(
      /(?:[\u2600-\u27BF]|[\uE000-\uF8FF]|[\uD83C-\uDBFF][\uDC00-\uDFFF]|[\u2700-\u27BF])/g,
      "",
    )
    // Also strip remaining surrogate pairs commonly used by emoji
    .replace(/[\uD800-\uDBFF][\uDC00-\uDFFF]/g, "");

  if (withoutEmoji.length > 0) return false;

  // Count rough emoji “slots” via remaining length of original compact form
  return compact.length > 0 && compact.length <= 36;
}
